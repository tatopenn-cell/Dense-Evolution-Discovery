# --- Funzioni ---
def S_boson(Delta_arr, beta):
    D = np.asarray(Delta_arr, dtype=float)
    x = beta * D
    ln_1m = np.empty_like(x)
    big = x > 50
    small = x < 1e-6
    mid = ~big & ~small
    ln_1m[big] = -np.exp(-x[big])
    ln_1m[small] = np.log(x[small])
    ln_1m[mid] = np.log1p(-np.exp(-x[mid]))
    ln_Z = -np.sum(ln_1m)
    E = np.sum(D / np.expm1(np.clip(x, 1e-12, 500)))
    return ln_Z + beta * E

def S_2states(Delta_arr, beta):
    D = np.asarray(Delta_arr, dtype=float)
    x = beta * D
    ln_Z = np.sum(np.logaddexp(0, -x))
    E = np.sum(D / (np.exp(np.clip(x, 0, 500)) + 1))
    return ln_Z + beta * E

