def lnZ_DVPT(beta, N):
    """Σ_p log(2 cosh(β ln p / 2)) — DVPT two-state"""
    x = beta * log_primes[:N] / 2
    return np.sum(np.logaddexp(x, -x))

def lnZ_fermi(beta, N):
    """Σ_p log(1 + p^{-β}) — fermionic zeta (ζ(β)/ζ(2β))"""
    return np.sum(np.logaddexp(0, -beta * log_primes[:N]))

