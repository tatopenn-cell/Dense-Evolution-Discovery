def compute_period(mu, u_max=1.0):
    E = u_max**4 / 2 - mu * u_max**2 / 2
    disc = mu**2 + 8 * E
    if disc < 0:
        return np.nan
    v = (mu + np.sqrt(disc)) / 2
    if v <= 0:
        return np.nan
    u_turn = np.sqrt(v)

    def integrand(u):
        val = 2 * (E - u**4/2 + mu * u**2/2)
        if val <= 1e-14:
            return 0.0
        return 1.0 / np.sqrt(val)

    try:
        T_half, _ = quad(integrand, 0, u_turn, limit=200)
    except Exception:
        return np.nan
    return 4 * T_half

