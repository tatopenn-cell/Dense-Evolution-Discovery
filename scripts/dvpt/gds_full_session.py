class GDSRealMatchedFiltering:
    def __init__(self, f_gr=251.0, f_gds=256.7, mass_solar=65.0):
        self.f_gr = f_gr
        self.f_gds = f_gds
        self.sample_rate = 16384.0  # Hz
        self.duration = 0.05        # 50 ms (finestra reale di ringdown transitorio)
        self.time_axis = np.arange(0, self.duration, 1.0 / self.sample_rate)

        # Tempo di smorzamento fisico (tau ~ 1 ms per GW150914)
        self.tau = 0.001 * (mass_solar / 65.0)
        self.gamma = 1.0 / self.tau

    def einstein_telescope_psd(self, f):
        """Modello analitico della curva di rumore Sn(f) di ET (sensibilità a 250 Hz)"""
        # Limite di sensibilità strumentale di terza generazione in banda centrale
        base_noise = 7e-24
        if f < 10.0: return 1e-18 # Cutoff sismico a bassa frequenza
        # Profilo di rumore parabolico semplificato attorno alla frequenza di picco
        return (base_noise * (1.0 + ((f - 250.0) / 100.0)**2))**2

    def compute_exact_frequency_snr(self):
        """Calcola il vero SNR differenziale integrando nel dominio di Fourier."""
        N = len(self.time_axis)
        df = self.sample_rate / N
        frequencies = np.fft.rfftfreq(N, 1.0 / self.sample_rate)

        # Generazione dei transitori reali smorzati (segnali fisici ad ampiezza standard h ~ 1e-21)
        amplitude_scale = 1e-21
        h_gr = amplitude_scale * np.exp(-self.gamma * self.time_axis) * np.cos(2 * np.pi * self.f_gr * self.time_axis)
        h_gds = amplitude_scale * np.exp(-self.gamma * self.time_axis) * np.cos(2 * np.pi * self.f_gds * self.time_axis)

        # Trasformata di Fourier dei segnali e del residuo
        tilde_delta_h = np.fft.rfft(h_gds - h_gr) / self.sample_rate

        # Integrazione di matched-filtering
        snr_sq = 0.0
        for idx, f in enumerate(frequencies):
            if f <= 0: continue
            Sn = self.einstein_telescope_psd(f)
            snr_sq += 4.0 * (np.abs(tilde_delta_h[idx])**2) * df / Sn

        return float(np.sqrt(snr_sq))

