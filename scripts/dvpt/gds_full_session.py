def gue_unfold(eigenvalues):
    N = len(eigenvalues)
    R = np.sqrt(2 * N)
    mask = np.abs(eigenvalues) < R
    ev = eigenvalues[mask]
    x = ev / R
    cdf = 0.5 + (x * np.sqrt(1 - x**2)) / np.pi + np.arcsin(x) / np.pi
    return np.sort(N * cdf)

