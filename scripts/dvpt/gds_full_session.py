def f_GDS_corrected(r, M=1.0, ell_sq=ell_zeta_sq, A=0.02, n_zeros=5):
    """
    Metrica GDS corretta:
    - Base: Jusufi-Anand f_JA(r) = 1 - 2M r/(r^2 + ell^2)
    - Correzione log-periodica: δf(r) ~ (M/r) e^{-3πr²/4} · oscillazione
    """
    f_base = 1 - 2*M*r / (r**2 + ell_sq)
    # Correzione log-periodica (Jusufi-Anand Eq. 43)
    envelope = np.exp(-3 * np.pi * r**2 / 4)
    oscillation = 0.0
    for t_n in zeros_Riemann[:n_zeros]:
        Xi_n = t_n * np.pi * r**2 / 2
        oscillation += (3/2) * np.cos(Xi_n) + t_n * np.sin(Xi_n)
    delta_f = -(M / r) * envelope * oscillation * A
    return f_base + delta_f

