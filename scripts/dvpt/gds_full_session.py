def P_functional_lattice(u, eps_AA):
    """Funzionale DVPT + potenziale quasiperiodico AA"""
    u_p = np.diff(u)
    kinetic = 0.5 * np.sum(u_p**2)
    potential_dvpt = 0.5 * np.sum(u**2 * (1 - u**2))
    potential_AA = eps_AA * np.sum(np.cos(2 * np.pi * alpha_AA * r_latt) * u)
    return kinetic + potential_dvpt + potential_AA

def gradient_P(u, eps_AA):
    """Gradiente del funzionale"""
    grad = np.zeros_like(u)
    u_pp = np.zeros_like(u)
    u_pp[1:-1] = u[2:] - 2*u[1:-1] + u[:-2]
    grad = -u_pp + u - 2*u**3 + eps_AA * np.cos(2*np.pi*alpha_AA*r_latt)
    grad[0] = 0
    grad[-1] = 0
    return grad

def relax(u0, eps_AA, n_steps=20000, dt=0.001):
    u = u0.copy()
    for _ in range(n_steps):
        g = gradient_P(u, eps_AA)
        u = u - dt * g
        u = np.clip(u, -2.0, 2.0)
    return u

