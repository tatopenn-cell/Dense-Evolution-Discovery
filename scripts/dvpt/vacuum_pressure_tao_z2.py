I2 = np.eye(2, dtype=complex)
XX = np.kron(X, X)

def random_2qubit_state():
    sv = np.random.normal(0, 1, 4) + 1j*np.random.normal(0, 1, 4)
    return sv / np.linalg.norm(sv)

def is_plus_one_eig(sv, tol=1e-8):
    return np.linalg.norm(XX @ sv - sv) < tol

hits_C = sum(1 for _ in range(N_trials) if is_plus_one_eig(random_2qubit_state()))
