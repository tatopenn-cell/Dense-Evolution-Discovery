# PARTE 3 — Cantor set in aritmetica intera esatta
# ============================================================
#
# Cantor set at level n: 2^n segments, each of length 1 in units
# of 3^-n. Start positions are integers in these units.
# Box count at scale 3^-k (k <= n): floor(a / 3^(n-k)) for each
# segment start a. This is exact integer arithmetic — no floats,
# no floor-of-float-ratio issues.
# ============================================================

def cantor_segments_int(n):
    """Cantor segments at level n, as integers scaled by 3^n.
    Level 0: [(0, 1)] — one segment of length 1 in units of 1.
    Level k: 2^k segments of length 1 in units of 3^-k.
    """
    if n == 0:
        return [(0, 1)]
    prev = cantor_segments_int(n - 1)
    out = []
    for a, b in prev:
        w = b - a
        out.append((3*a, 3*a + w))
        out.append((3*b - w, 3*b))
    return out


D_theory = np.log(2) / np.log(3)
print("=" * 60)
print("PARTE 3 — Auto-similarità: insieme di Cantor")
print("=" * 60 + "\n")
print(f"D_teorico = log(2)/log(3) = {D_theory:.4f}\n")

for n in [2, 3, 4, 5, 6, 7, 8]:
    segs = cantor_segments_int(n)
    ks = list(range(1, n + 1))
    # Exact integer box count at each scale 3^-k
    counts = []
    for k in ks:
        divisor = 3**(n - k)
        boxes = set(a // divisor for (a, b) in segs)
        counts.append(len(boxes))
    scales = [3.0**(-k) for k in ks]
    D = -np.polyfit(np.log(scales), np.log(counts), 1)[0]
    match = "✓" if counts == [2**k for k in ks] else "✗"
    print(f"[n={n}]  counts = {counts}   D = {D:.4f}  {match}")

print(f"\nD = {D_theory:.4f} esatto per ogni n ≥ 2\n")


