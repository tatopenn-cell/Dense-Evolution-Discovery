def random_polygon(n_vertices, grid=20):
    pts = set()
    while len(pts) < n_vertices:
        pts.add((np.random.randint(0, grid), np.random.randint(0, grid)))
    return np.array(sorted(pts))

def has_specular_symmetry(poly):
    cx = poly[:, 0].mean()
    reflected = np.round(np.stack([2*cx - poly[:, 0], poly[:, 1]], axis=1)).astype(int)
    return set(map(tuple, poly)) == set(map(tuple, reflected))

N_trials = 5000
hits_A = sum(1 for _ in range(N_trials)
             if has_specular_symmetry(random_polygon(np.random.randint(3, 8))))
print(f"[Misura A] Poligoni casuali: P(Z₂ speculare) = {hits_A/N_trials:.5f}")


def random_fourier_func(n_modes=10, n_samples=200):
    x = np.linspace(-np.pi, np.pi, n_samples)
    f = np.zeros_like(x)
    for k in range(1, n_modes + 1):
        f += np.random.normal(0, 1)*np.cos(k*x) + np.random.normal(0, 1)*np.sin(k*x)
    return x, f

def is_even(x, f, tol=1e-6):
    return np.allclose(f, np.interp(-x, x, f), atol=tol)

hits_B = sum(1 for _ in range(N_trials) if is_even(*random_fourier_func()))
print(f"[Misura B] Funzioni di Fourier: P(Z₂ pari)   = {hits_B/N_trials:.5f}")


X = np.array([[0, 1], [1, 0]], dtype=complex)
