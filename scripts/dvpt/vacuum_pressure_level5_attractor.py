def P_functional(u):
    """
    P[u] = ∫ [ (u')²/2 + u²(1-u²)/2 ] dr

    Questa forma ha u = sech(r) come soluzione stazionaria:
    u'' = u - 2u³
    """
    u_p = np.gradient(u, dr)
    kinetic = 0.5 * np.sum(u_p**2) * dr
    potential = 0.5 * np.sum(u**2 * (1 - u**2)) * dr
    return kinetic + potential

def dP_du(u):
    """
    δP/δu = -u'' + u - 2u³
    Dinamica: ∂u/∂t = -δP/δu = u'' - u + 2u³
    """
    u_pp = np.gradient(np.gradient(u, dr), dr)
    return -u_pp + u - 2*u**3

def dynamics(t, u_flat):
    u = u_flat.reshape(N)
    du = -dP_du(u)
    # Boundary conditions: u → 0 a r grande, u' → 0 a r=0
    du[0] = 0
    du[-1] = 0
    return du.flatten()

# ============================================================
# RIFERIMENTO — sech
# ============================================================
def sech_ref(r, n=1):
    return 1.0 / np.cosh((r/ell0)**n)

