# ============================================================
def sech_ref(r, ell0=1.0, n=1):
    return 1.0 / np.cosh((r/ell0)**n)

def run_test(N, r_max=15.0, T=100.0):
    r = np.linspace(1e-4, r_max, N)
    dr = r[1] - r[0]
    ell0 = 1.0

    def P_functional(u):
        u_p = np.gradient(u, dr)
        return 0.5*np.sum(u_p**2)*dr + 0.5*np.sum(u**2*(1-u**2))*dr

    def dP_du(u):
        u_pp = np.gradient(np.gradient(u, dr), dr)
        return -u_pp + u - 2*u**3

    def dynamics(t, u_flat):
        u = u_flat.reshape(N)
        du = -dP_du(u)
        du[0] = 0
        du[-1] = 0
        return du.flatten()

    iniziali = {
        'gauss':  np.exp(-r**2/2),
        'exp':    np.exp(-r),
        'picco':  0.8*np.exp(-((r-0.5)/0.5)**2) + 0.4*np.exp(-((r-3)/1.0)**2),
        'rumore': 0.3 + 0.3*np.exp(-r/2)*np.cos(2*r),
    }

    u_finals = []
    Ps = []
    for nome, u0 in iniziali.items():
        sol = solve_ivp(dynamics, [0, T], u0.flatten(),
                        method='LSODA', rtol=1e-8, atol=1e-10)
        # Prendi l'ultimo punto disponibile
        u_f = np.clip(sol.y[:, -1].reshape(N), -2, 2)
        u_finals.append(u_f)
        Ps.append((P_functional(u0), P_functional(u_f)))

    u_finals = np.array(u_finals)
    u_mean = u_finals.mean(axis=0)
    u_std = u_finals.std(axis=0)

    amp = np.max(np.abs(u_mean))
    u_sech = amp * sech_ref(r, ell0, n=1)
    corr = np.corrcoef(u_mean, u_sech)[0, 1]

    L2_err = np.sqrt(np.sum((u_mean - u_sech)**2)*dr) / np.sqrt(np.sum(u_sech**2)*dr)
    div = np.max(u_std / (np.abs(u_mean) + 1e-10))
    Pf = P_functional(u_mean)
    monotona = all(P0 > Pf_ for P0, Pf_ in Ps)

    return corr, L2_err, div, Pf, monotona, r, u_mean, u_sech

# ============================================================
Ns = [200, 500, 1000, 2000]
risultati = {}

print(f"\n {'N':>6} {'corr':>12} {'L2 err':>14} {'diverge':>10} {'P_final':>12} {'monot':>6}")
