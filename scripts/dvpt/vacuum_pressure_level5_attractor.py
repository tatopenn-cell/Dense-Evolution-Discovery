import numpy as np

print("=" * 80)
print(" LIVELLO 5 — Test C (Eulero esplicito)")
print("=" * 80)

N = 200
r_max = 10.0
r = np.linspace(1e-3, r_max, N)
dr = r[1] - r[0]
dt = 0.001
T_steps = 5000  # t_finale = 5.0

def sech_ref(r):
    return 1.0 / np.cosh(r)

def evolve(V_prime, u0, steps=T_steps, dt=dt):
    """Eulero esplicito: u_{n+1} = u_n + dt·(u'' - V'(u))"""
    u = u0.copy()
    for _ in range(steps):
        u_pp = np.zeros_like(u)
        u_pp[1:-1] = (u[2:] - 2*u[1:-1] + u[:-2]) / dr**2
        du = u_pp - V_prime(u)
        du[0] = 0
        du[-1] = 0
        u = u + dt * du
        # Clippa per sicurezza
        u = np.clip(u, -5, 5)
    return u

# ============================================================
# 2 POTENZIALI
# ============================================================
potenziali = {
    'P1': (lambda u: u - 2*u**3),
    'P2': (lambda u: 2*u - 4*u**3),
}

u0 = np.exp(-r**2 / 2)

print(f"\n {'Potenziale':>12} {'corr':>10} {'amp':>8}")
print(" " + "─" * 34)

for label, Vp in potenziali.items():
    u_f = evolve(Vp, u0)
    amp = np.max(np.abs(u_f))
    if amp < 1e-6:
        print(f" {label:>12}  u→0")
        continue
    u_n = u_f / amp
    corr = np.corrcoef(u_n, sech_ref(r))[0, 1]
    print(f" {label:>12} {corr:>10.6f} {amp:>8.4f}")

