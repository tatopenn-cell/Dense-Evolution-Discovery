"""
Steane code [[7,1,3]] -- block 1: encode, verify, syndrome-decode, correct.

Encoding circuit
-----------------
CSS(C1, C2) construction where C1 is the classical Hamming [7,4,3] code
(16 codewords, null space of H below) and C2 is its dual, the [7,3,4]
simplex code generated BY H's rows (8 codewords) -- C2 subset C1 is
exactly the "dual-containing" property that makes the Steane code work.
|0>_L is the uniform superposition over C2's 8 codewords, NOT over all 16
codewords of C1 (an earlier version of this script superposed over all
16, which is actually (|0>_L + |1>_L)/sqrt(2): C1 = C2 union (C2 + 1),
where 1 = 1111111 is itself a codeword of C1 but not of C2, so summing
over all of C1 mixes both logical values -- caught by the <Z_L> = 0
check below on the first run, not assumed correct).

    H = [0 0 0 1 1 1 1]   r1
        [0 1 1 0 0 1 1]   r2
        [1 0 1 0 1 0 1]   r3

Using 1-indexed qubit labels c1..c7 (0-indexed q0..q6): columns 4, 2, 1
of H are exactly e1, e2, e3 (an identity submatrix), so c4, c2, c1
(0-indexed q3, q1, q0) are a systematic set of 3 free/information qubits
for C2, and the other 4 are CNOT-derived from them:

    c3 = c1 (+) c2            c5 = c1 (+) c4
    c6 = c2 (+) c4             c7 = c1 (+) c2 (+) c4

Putting q0, q1, q3 into an equal H superposition and CNOT-deriving
q2, q4, q5, q6 from them produces exactly (1/sqrt(8)) * sum over C2's 8
codewords -- |0>_L. This matches the X-stabilizers given below
column-for-column (verified directly, not just asserted): row 1 of H is
IIIXXXX, row 2 is IXXIIXX, row 3 is XIXIXIX.

|1>_L is obtained by applying the logical X (X on all 7 qubits, i.e. XOR
with 1111111) to |0>_L -- 1111111 is a codeword of C1 but not of C2
(verified: no combination of r1/r2/r3 sums to it), so this maps C2's
coset to the other coset of C2 within C1, the correct construction for
the orthogonal logical-1 subspace.

Syndrome extraction
--------------------
This first pass uses direct expectation-value syndrome computation
(pauli_expectation on the full statevector) rather than ancilla-based
measurement circuits. This is legitimate here because every state this
script's syndrome ever gets computed on is a *known* Pauli string applied
to a stabilizer state, so pauli_expectation always returns an exact +-1
(not just "close to" -- verified below), the same information a real
ancilla measurement would collapse to, without needing to model the extra
ancilla qubits, CNOTs, and measurement collapse. Genuine ancilla-based
extraction (and dealing with the mid-circuit measurement collapse that
comes with it) is left for a later block once this baseline is verified.

Noise regimes
--------------
Section 4 (syndrome table + single-error correction) uses deterministic,
hand-injected single-qubit Pauli gates -- this is the right tool to
reproduce the textbook syndrome table and check the decoder's logic
against it exactly, one error at a time, with no sampling noise.

Section 5 (logical vs. physical error rate) uses NoiseModel's real
stochastic depolarizing Kraus channel applied independently to all 7
qubits at once, many trials per physical error rate p -- this is the
regime that actually stresses the distance-3 decoder (which only ever
proposes a single-qubit correction) with realistic multi-qubit error
events.
"""
