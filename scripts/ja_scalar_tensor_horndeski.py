mask_pos = phi_p_sq > 0

if np.any(mask_pos):
    phi_p = np.sqrt(np.where(mask_pos, phi_p_sq, 0))
    phi_arr = np.zeros_like(r_grid)
    for i in range(1, len(r_grid)):
        dr = r_grid[i] - r_grid[i-1]
        phi_arr[i] = phi_arr[i-1] + 0.5 * (phi_p[i] + phi_p[i-1]) * dr

    # Compute V from the (t,t) equation:
    # kappa V = -F G^t_t - f F'' - (f'/2) F' - 2f F'/r - kappa(f/2)(phi')^2
    # with kappa = 1
    f_val = f_JA(r_grid)
    fp_val = fp_JA(r_grid)
    Gtt_val = G_tt(r_grid)

    V_arr = -F_arr * Gtt_val - f_val * Fpp_arr - (fp_val/2) * Fp_arr \
            - 2 * f_val * Fp_arr / r_grid - (f_val/2) * phi_p_sq

    print(f"  phi(r) range: [{phi_arr.min():.6e}, {phi_arr.max():.6e}]")
    print(f"  V(r) range: [{V_arr.min():.6e}, {V_arr.max():.6e}]")

    print(f"\n  Single-valuedness test for V(phi):")

    idx_sort = np.argsort(phi_arr)
    phi_sorted = phi_arr[idx_sort]
    V_sorted = V_arr[idx_sort]

    dphi = np.diff(phi_sorted)
    print(f"  Is phi monotonic? Number of negative dphi: {np.sum(dphi < 0)}")

    if np.all(dphi >= 0):
        print(f"  -> phi(r) is monotonic. V(phi) is well defined.")
    else:
        print(f"  -> phi(r) is NOT monotonic. V(phi) may be multi-valued.")

    phi_bins = np.linspace(phi_arr[mask_pos].min(), phi_arr[mask_pos].max(), 30)
    for phi_target in phi_bins[:10]:
        idx_near = np.where(np.abs(phi_arr - phi_target) < 0.1)[0]
        if len(idx_near) > 0:
            V_at_phi = V_arr[idx_near]
            spread = V_at_phi.max() - V_at_phi.min()
            print(f"    phi = {phi_target:.4f}: {len(idx_near)} points, "
                  f"V spread = {spread:.4e}")

    r_data = r_grid
    F_data = F_arr
    Fp_data = Fp_arr
    Fpp_data = Fpp_arr
    phi_data = phi_arr
    V_data = V_arr
    phi_p_sq_data = phi_p_sq

else:
    print("  (phi')^2 is always <= 0 -> no real scalar solution")

