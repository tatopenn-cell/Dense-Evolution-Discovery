#   (2*pi/hbar*eta) T_ab = R_ab - nabla_a nabla_b rho + f g_ab
#   with e^rho = dS/dA
#
# For S(A) = A/4G + alpha ln(A/A_0):
#   dS/dA = 1/4G + alpha/A
#   rho(A) = ln(1/4G + alpha/A)
#
# Test: for the JA metric, is rho(r) a local function of R(r)?
#   If yes: rho = F(R) -> a local f(R) theory
#   If no: the term is non-local -> no local Lagrangian
# ==============================================================================

import numpy as np
