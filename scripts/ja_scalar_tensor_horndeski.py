# SCALAR-TENSOR TEST -- is the JA metric a solution of F(phi)R - 1/2(d.phi)^2 - V(phi)?
# ==============================================================================
# Procedure:
# 1. From the JA metric, solve F(r) from equation (theta-theta)-(t-t):
#       F (G^theta_theta - G^t_t) = f F'/r - (f'/2) F'
# 2. Check F'' < 0  ->  (phi')^2 = -F''
# 3. Compute V(r) from equation (t,t)
# 4. Check whether (phi(r), V(r)) is a single-valued curve -> V(phi) exists
# ==============================================================================

import numpy as np
import matplotlib.pyplot as plt

line = "=" * 78

G = 1.0
ell_sq = G / np.pi
M = 1.0

# ------------------------------------------------------------------------------
# Metric and Einstein tensor (exact closed forms)
# ------------------------------------------------------------------------------
def f_JA(r):
    return 1 - 2*G*M*r/(r**2 + ell_sq)

def fp_JA(r):
    return 2*G*M*(r**2 - ell_sq)/(r**2 + ell_sq)**2

def fpp_JA(r):
    return 4*G*M*r*(3*ell_sq - r**2)/(r**2 + ell_sq)**3

def G_tt(r):
    """G^t_t = G^r_r = (f + rf' - 1)/r^2"""
    return (f_JA(r) + r*fp_JA(r) - 1) / r**2

def G_thth(r):
    """G^theta_theta = f''/2 + f'/r"""
    return fpp_JA(r)/2 + fp_JA(r)/r

def A_fun(r):
    """A(r) = G^theta_theta - G^t_t"""
    return G_thth(r) - G_tt(r)

def B_fun(r):
    """B(r) = f/r - f'/2"""
    return f_JA(r)/r - fp_JA(r)/2

# ------------------------------------------------------------------------------
# [1] Verify closed-form Einstein tensor against numerical
# ------------------------------------------------------------------------------
print(line)
print(" [1] Verify Einstein-tensor formulas")
print(line)

def f_num(r):
    return 1 - 2*G*M*r/(r**2 + ell_sq)

def f_derivs_num(r):
    h = 1e-6 * r
    fp = (f_num(r + h) - f_num(r - h)) / (2*h)
    fpp = (f_num(r + h) - 2*f_num(r) + f_num(r - h)) / h**2
    return fp, fpp

print(f"  {'r':>8} {'G^t_t (formula)':>18} {'G^t_t (num)':>18} "
      f"{'G^thth (formula)':>18} {'G^thth (num)':>18}")
print("  " + "-" * 84)
for r_test in [0.2, 0.5, 1.0, 2.0, 5.0, 10.0]:
    G_tt_form = G_tt(r_test)
    G_th_form = G_thth(r_test)
    fp, fpp = f_derivs_num(r_test)
    G_tt_num = (f_num(r_test) + r_test*fp - 1)/r_test**2
    G_th_num = fpp/2 + fp/r_test
    print(f"  {r_test:>8.3f} {G_tt_form:>18.10f} {G_tt_num:>18.10f} "
          f"{G_th_form:>18.10f} {G_th_num:>18.10f}")

# ------------------------------------------------------------------------------
# [2] Solve F(r) from ODE: F'/F = A/B
# ------------------------------------------------------------------------------
