r_grid = np.logspace(-3, 3, 8000)
A_arr = A_fun(r_grid)
B_arr = B_fun(r_grid)

if np.any(B_arr == 0):
    print(f"  WARN: B(r) = 0 at some point. Handling with care.")
    B_arr = np.where(np.abs(B_arr) < 1e-30, 1e-30, B_arr)

ratio = A_arr / B_arr

i_ref = np.argmin(np.abs(r_grid - 5.0))
lnF = np.zeros_like(r_grid)

for i in range(i_ref + 1, len(r_grid)):
    dr = r_grid[i] - r_grid[i-1]
    lnF[i] = lnF[i-1] + 0.5 * (ratio[i] + ratio[i-1]) * dr

for i in range(i_ref - 1, -1, -1):
    dr = r_grid[i] - r_grid[i+1]
    lnF[i] = lnF[i+1] + 0.5 * (ratio[i] + ratio[i+1]) * dr

F_arr = np.exp(lnF)

print(f"  F(r) range: [{F_arr.min():.6e}, {F_arr.max():.6e}]")
print(f"  F(5) = {F_arr[i_ref]:.10f}")
