print(f"  F(0.01) = {np.interp(0.01, r_grid, F_arr):.10f}")
print(f"  F(100) = {np.interp(100, r_grid, F_arr):.10f}")

# ------------------------------------------------------------------------------
# [3] Compute F', F'' and check F'' < 0
# ------------------------------------------------------------------------------
print(f"\n{line}")
print(" [3] F', F'' and checking F'' < 0")
