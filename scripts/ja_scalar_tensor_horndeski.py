# ------------------------------------------------------------------------------
# JA metric setup
# ------------------------------------------------------------------------------
# f(r) = 1 - 2GMr/(r^2 + ell^2),  ell^2 = G/pi
# Units: G = 1, M a parameter, ell^2 = 1/pi

G = 1.0
ell_sq = G / np.pi
alpha = 1.0

def f_JA(r, M):
    return 1 - 2*G*M*r / (r**2 + ell_sq)

def R_JA(r, M):
    """Ricci scalar for a static spherical metric: R = -f'' - 4f'/r + 2(1-f)/r^2"""
    h = 1e-7 * max(r, 0.01)
    f_val = f_JA(r, M)
    fp = (f_JA(r + h, M) - f_JA(r - h, M)) / (2 * h)
    fpp = (f_JA(r + h, M) - 2*f_val + f_JA(r - h, M)) / h**2
    return -fpp - 4*fp/r + 2*(1 - f_val)/r**2

def find_horizon(M):
    """Finds r_h such that f(r_h) = 0."""
    try:
        return brentq(lambda r: f_JA(r, M), 1e-8, 10 * 2 * M + 10)
    except ValueError:
        return np.nan

