phi_p_sq = -Fpp_arr

print(f"  F'' range: [{Fpp_arr.min():.4e}, {Fpp_arr.max():.4e}]")
print(f"  (phi')^2 = -F'' range: [{phi_p_sq.min():.4e}, {phi_p_sq.max():.4e}]")
frac_pos = np.mean(phi_p_sq > 0)
print(f"  Fraction of points with (phi')^2 > 0: {frac_pos*100:.2f}%")

# ------------------------------------------------------------------------------
# [4] Compute phi(r) = int sqrt(-F'') dr and V(r)
